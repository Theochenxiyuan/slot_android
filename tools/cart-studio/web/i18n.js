export function t(text) {
  if (!chinese || typeof text !== 'string') return text;
  if (Object.hasOwn(WORDS, text)) return WORDS[text];
  for (const [pattern, replace] of PATTERNS) if (pattern.test(text)) return text.replace(pattern, replace);
  return text;
}

// The static page: text nodes and the labels assistive tech and tooltips read.
export function translatePage(root = document.body) {
  if (!chinese) return;
  document.documentElement.lang = 'zh-CN';
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const text = node.nodeValue.trim();
    if (text && Object.hasOwn(WORDS, text)) node.nodeValue = node.nodeValue.replace(text, WORDS[text]);
  }
  for (const el of root.querySelectorAll('[aria-label],[title]')) {
    for (const name of ['aria-label', 'title']) {
      const value = el.getAttribute(name);
      if (value && Object.hasOwn(WORDS, value)) el.setAttribute(name, WORDS[value]);
    }
  }
  for (const template of root.querySelectorAll('template')) translatePage(template.content);
}
